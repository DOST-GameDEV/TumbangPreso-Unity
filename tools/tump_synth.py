"""TUMP's sound synthesiser: learn an object from a reference recording, then generate it from the numbers.

Owner, 2026-10-23: "i wanted u to learn how to use a synthesizer or audio generation shit for our game tump", and
chose "synth, learned from refs": every shipped sound is generated by code; CC0 recordings are only MEASURED.

Two halves, both numpy/scipy only:
  ANALYSIS   modal(x)     the partials of a struck or plucked thing: frequency, level, decay rate (dB/s) each
             texture(x)   a noisy thing: its spectrum in sixth-octave bands, attack, decay, grain rate
             creak(x)     a stick-slip sound: its pulse-rate track over time and the body's resonances
  SYNTHESIS  strike(...)  a modal bank excited by a mallet (soft = dark, hard = bright), plus its contact click
             noise_like(...)  noise coloured to a measured spectrum
             grains(...)  a scrape: short coloured-noise grains at a measured rate
             stick_slip(...)  a creak: a jittered pulse train at a pitch track, through the body's resonances
             room(...)    THE one room every TUMP file shares (a small concrete alley), and the house filters

Profiles are plain dicts (JSON-able), written by a build script's analyse step and committed, so a rebuild needs
neither the network nor the reference files. Fixed seeds everywhere: same profile, same bytes.
"""
import numpy as np
from scipy import signal

SR = 44100
NOTE = {"C": 0, "C#": 1, "D": 2, "D#": 3, "E": 4, "F": 5, "F#": 6, "G": 7, "G#": 8, "A": 9, "A#": 10, "B": 11}


def hz(name):
    """'C5' style note name to Hz (A4 = 440)."""
    return 440.0 * 2 ** ((NOTE[name[:-1]] + 12 * (int(name[-1]) + 1) - 69) / 12)


def t_of(seconds):
    return np.arange(int(SR * seconds)) / SR


# ------------------------------------------------------------------ analysis

def onset(x, frac=0.1):
    """The first sample above `frac` of the peak, less 2 ms."""
    i = int(np.argmax(np.abs(x) > frac * np.abs(x).max()))
    return max(0, i - int(0.002 * SR))


def envelope_db(x, ms=5.0):
    n = max(1, int(SR * ms / 1000))
    env = np.sqrt(np.convolve(x * x, np.ones(n) / n, mode="same")) + 1e-9
    return 20 * np.log10(env / env.max())


def modal(x, at=None, partials=10, window=0.15, lo=50.0, hi=16000.0, near=None):
    """The strongest partials after the strike: [{f, db, decay}] sorted by frequency.
    db is relative to the loudest partial; decay is how fast each one dies, in dB per second.
    `near` (Hz) forces the partial closest to it to be reported first as the fundamental."""
    a = onset(x) if at is None else int(at * SR)
    a += int(0.004 * SR)                                   # past the contact click
    n = int(window * SR)
    seg = x[a:a + n]
    seg = seg * np.hanning(len(seg))
    nfft = 1 << 17
    mag = np.abs(np.fft.rfft(seg, nfft))
    freqs = np.fft.rfftfreq(nfft, 1 / SR)
    db = 20 * np.log10(mag / mag.max() + 1e-12)
    band = (freqs > lo) & (freqs < hi)
    peaks, _ = signal.find_peaks(np.where(band, db, -200), prominence=8, distance=int(25 / (SR / nfft)))
    peaks = [p for p in peaks if db[p] > -48]
    peaks = sorted(peaks, key=lambda p: -db[p])[:partials]
    # decay of each partial: track its band over 1.5 s (or what there is) in 10 ms hops
    hop, win = int(0.01 * SR), 4096
    tail = x[a:a + int(min(2.5, (len(x) - a) / SR) * SR)]
    out = []
    for p in peaks:
        f = freqs[p]
        k = np.arange(win)
        probe = np.exp(-2j * np.pi * f * k / SR) * np.hanning(win)
        track = []
        for s in range(0, max(1, len(tail) - win), hop):
            track.append(abs(np.dot(tail[s:s + win], probe)))
        track = 20 * np.log10(np.asarray(track) + 1e-12)
        top = int(np.argmax(track[:20])) if len(track) else 0
        live = track[top:]
        live = live[: max(3, int(np.argmax(live < live[0] - 40)) or len(live))]
        times = np.arange(len(live)) * hop / SR
        decay = -np.polyfit(times, live, 1)[0] if len(live) >= 3 else 60.0
        out.append({"f": round(float(f), 2), "db": round(float(db[p]), 1), "decay": round(float(max(decay, 1.0)), 1)})
    out.sort(key=lambda d: d["f"])
    if near is not None and out:
        root = min(out, key=lambda d: abs(np.log2(d["f"] / near)))
        out.remove(root)
        out.insert(0, root)
    return out


SIXTH_OCTAVES = [round(float(f), 1) for f in 62.5 * 2 ** (np.arange(0, 48) / 6) if f < 17000]


def texture(x, at=None, length=None):
    """A noisy event: its spectrum (dB per sixth-octave band, loudest 0), attack (ms, 10 % to peak),
    decay (ms from peak to -20 dB and to -40 dB), and the grain rate (envelope peaks per second)."""
    a = onset(x) if at is None else int(at * SR)
    b = len(x) if length is None else min(len(x), a + int(length * SR))
    seg = x[a:b]
    spec = np.abs(np.fft.rfft(seg * np.hanning(len(seg)), 1 << 16)) ** 2
    freqs = np.fft.rfftfreq(1 << 16, 1 / SR)
    bands = []
    for f in SIXTH_OCTAVES:
        sel = (freqs >= f * 2 ** (-1 / 12)) & (freqs < f * 2 ** (1 / 12))
        bands.append(10 * np.log10(spec[sel].mean() + 1e-20))
    bands = np.asarray(bands) - max(bands)
    env = envelope_db(seg, 2.0)
    peak = int(np.argmax(env))
    rise = int(np.argmax(env[: peak + 1] > -20)) if peak > 0 else 0
    after = env[peak:]
    d20 = int(np.argmax(after < -20)) if np.any(after < -20) else len(after)
    d40 = int(np.argmax(after < -40)) if np.any(after < -40) else len(after)
    smooth = envelope_db(seg, 8.0)
    pk, _ = signal.find_peaks(smooth, prominence=4, distance=int(0.012 * SR))
    return {"bands": [round(float(v), 1) for v in bands], "attack_ms": round((peak - rise) / SR * 1000, 2),
            "decay20_ms": round(d20 / SR * 1000, 1), "decay40_ms": round(d40 / SR * 1000, 1),
            "grains_per_s": round(len(pk) / max(len(seg) / SR, 1e-3), 1), "seconds": round(len(seg) / SR, 3)}


def creak(x, at, length, lo=25.0, hi=900.0):
    """A creak: its stick-slip pulse rate every 20 ms (autocorrelation), and the body resonances under it."""
    a, n = int(at * SR), int(length * SR)
    seg = x[a:a + n]
    hop, win = int(0.02 * SR), int(0.06 * SR)
    track = []
    for s in range(0, len(seg) - win, hop):
        w = seg[s:s + win] * np.hanning(win)
        ac = np.correlate(w, w, "full")[win - 1:]
        lag_lo, lag_hi = int(SR / hi), int(SR / lo)
        lag = lag_lo + int(np.argmax(ac[lag_lo:lag_hi]))
        strength = ac[lag] / (ac[0] + 1e-12)
        track.append(round(float(SR / lag), 1) if strength > 0.25 else 0.0)
    body = modal(seg, at=0.0, partials=6, window=min(length, 0.3), lo=300, hi=6000)
    return {"rate": track, "hop_s": 0.02, "body": body, "seconds": round(length, 3)}


# ------------------------------------------------------------------ synthesis

def mallet_weight(f, hardness):
    """How much a mallet excites frequency f: a half-sine contact of width set by hardness (0 soft .. 1 hard)."""
    width = 0.0035 * (1.0 - hardness) + 0.00025
    w = np.pi * f * width
    return np.abs(np.cos(w) / np.maximum(1 - (2 * w / np.pi) ** 2, 1e-3))


def strike(partials, seconds, pitch=1.0, hardness=0.6, seed=0, decay_scale=1.0, click=0.15, brightness=1.0, f_ref=None):
    """A modal bank: each measured partial as a decaying sine, weighted by the mallet, plus a short contact click.
    `pitch` moves every partial together (a different note of the same instrument); higher notes of a real bar die
    faster, so decays scale gently with pitch. `brightness` tilts the upper partials."""
    rng = np.random.default_rng(seed)
    t = t_of(seconds)
    y = np.zeros_like(t)
    f0 = partials[0]["f"] if f_ref is None else f_ref
    for p in partials:
        f = p["f"] * pitch
        if f >= SR * 0.45:
            continue
        amp = 10 ** (p["db"] / 20) * mallet_weight(f, hardness) * (f / f0) ** (0.35 * (brightness - 1.0))
        d = p["decay"] * decay_scale * pitch ** 0.35 / 8.686
        y += amp * np.sin(2 * np.pi * f * t + rng.uniform(0, 2 * np.pi)) * np.exp(-d * t)
    if click > 0:
        n = int(0.004 * SR)
        c = rng.normal(0, 1, n) * np.exp(-np.arange(n) / (0.0007 * SR))
        c = band(c, 300 + 2500 * hardness, 1500 + 7500 * hardness)      # a soft mallet's contact is dark, a hard one bright
        y[:n] += click * c * np.abs(y).max() / (np.abs(c).max() + 1e-9)
    return fade(y, 0.0004, 0.03)


def noise_like(bands, seconds, seed=0, tilt_db=0.0):
    """White noise coloured to a measured sixth-octave spectrum (plus an optional tilt in dB per octave)."""
    rng = np.random.default_rng(seed)
    n = int(seconds * SR)
    spec = np.fft.rfft(rng.normal(0, 1, n))
    freqs = np.fft.rfftfreq(n, 1 / SR)
    centres = np.asarray(SIXTH_OCTAVES[: len(bands)])
    gain_db = np.interp(np.log2(np.maximum(freqs, 20)), np.log2(centres), np.asarray(bands), left=bands[0] - 12, right=bands[-1] - 12)
    gain_db += tilt_db * np.log2(np.maximum(freqs, 20) / 1000)
    y = np.fft.irfft(spec * 10 ** (gain_db / 20), n)
    return y / (np.abs(y).max() + 1e-12)


def burst(bands, attack_ms, decay20_ms, seed=0, seconds=None, tilt_db=0.0):
    """One noisy event (a clap, a slap): coloured noise under its measured attack and exponential decay."""
    seconds = seconds or max(0.05, decay20_ms * 3.2 / 1000)
    y = noise_like(bands, seconds, seed, tilt_db)
    t = t_of(seconds)
    rise = np.clip(t / max(attack_ms / 1000, 0.0002), 0, 1)
    tau = max(decay20_ms / 1000, 0.002) / np.log(10)          # -20 dB at decay20
    return fade(y * rise * np.exp(-np.maximum(t - attack_ms / 1000, 0) / tau), 0.0002, 0.01)


def grains(bands, seconds, rate, seed=0, grain_ms=(6, 22), level=(0.35, 1.0), speed=None, bed=0.12):
    """A scrape: grains of coloured noise. `rate` grains a second (or `speed`, an array over time, scaling it),
    each grain a random length and level, over a quiet continuous bed of the same colour."""
    rng = np.random.default_rng(seed)
    n = int(seconds * SR)
    src = noise_like(bands, seconds + 0.1, seed + 1)
    y = bed * src[:n].copy()
    at = 0.0
    while at < seconds:
        g = rng.uniform(*grain_ms) / 1000
        i, m = int(at * SR), int(g * SR)
        if i + m >= n:
            break
        shape = np.hanning(m) ** 0.6
        y[i:i + m] += rng.uniform(*level) * src[i:i + m] * shape
        k = 1.0 if speed is None else float(np.interp(at, np.linspace(0, seconds, len(speed)), speed))
        at += rng.exponential(1.0 / max(rate * k, 1.0))
    return y


def stick_slip(rate_track, hop_s, body, seconds, seed=0, jitter=0.08, rate_scale=1.0):
    """A creak: a pulse at every slip, the slip rate following `rate_track` (Hz every hop_s), jittered like real
    friction, each pulse ringing the body's measured resonances."""
    rng = np.random.default_rng(seed)
    n = int(seconds * SR)
    pulses = np.zeros(n)
    rates = np.asarray(rate_track, dtype=float)
    times = np.arange(len(rates)) * hop_s
    valid = rates > 0
    rates = np.interp(times, times[valid], rates[valid]) if valid.any() else np.full_like(times, 120.0)
    at = 0.0
    while at < seconds:
        r = float(np.interp(at * len(rates) * hop_s / seconds, times, rates)) * rate_scale
        i = int(at * SR)
        if i >= n:
            break
        pulses[i] += rng.uniform(0.6, 1.0)
        at += (1.0 / max(r, 15.0)) * (1 + rng.uniform(-jitter, jitter))
    y = np.zeros(n)
    for p in body:
        f = p["f"]
        if f >= SR * 0.45:
            continue
        r = np.exp(-np.pi * max(p["decay"] / 8.686 / np.pi, 180.0) / SR)       # wide: a slip rings wood briefly, it does not sing
        b, a = [1 - r], [1, -2 * r * np.cos(2 * np.pi * f / SR), r * r]
        y += 10 ** (p["db"] / 20) * signal.lfilter(b, a, pulses)
    return y / (np.abs(y).max() + 1e-12)


# ------------------------------------------------------------------ the house filters and THE room

def lowpass(x, cut, order=2):
    return signal.sosfilt(signal.butter(order, min(cut, SR * 0.45), "low", fs=SR, output="sos"), x)


def highpass(x, cut, order=2):
    return signal.sosfilt(signal.butter(order, cut, "high", fs=SR, output="sos"), x)


def band(x, low, high, order=2):
    return signal.sosfilt(signal.butter(order, [low, min(high, SR * 0.45)], "band", fs=SR, output="sos"), x)


def peak_eq(x, f, gain_db, q=1.0):
    """One bell EQ band (RBJ cookbook)."""
    A, w = 10 ** (gain_db / 40), 2 * np.pi * f / SR
    alpha = np.sin(w) / (2 * q)
    b = [1 + alpha * A, -2 * np.cos(w), 1 - alpha * A]
    a = [1 + alpha / A, -2 * np.cos(w), 1 - alpha / A]
    return signal.lfilter(np.asarray(b) / a[0], np.asarray(a) / a[0], x)


def fade(x, fade_in=0.004, fade_out=0.03):
    y = np.asarray(x, dtype=float).copy()
    a, b = min(len(y) // 2, int(SR * fade_in)), min(len(y) // 2, int(SR * fade_out))
    if a > 0:
        y[:a] *= 0.5 - 0.5 * np.cos(np.linspace(0, np.pi, a))
    if b > 0:
        y[-b:] *= 0.5 + 0.5 * np.cos(np.linspace(0, np.pi, b))
    return y


def shift(x, semitones):
    """Resample to a new pitch (and length), as an AudioSource's pitch does."""
    if abs(semitones) < 1e-6:
        return x
    ratio = 2 ** (semitones / 12)
    idx = np.arange(0, len(x) - 1, ratio)
    return np.interp(idx, np.arange(len(x)), x)


def place(track, clip, at, gain=1.0):
    i = int(round(at * SR))
    if i >= len(track) or i < 0:
        return
    j = min(len(track), i + len(clip))
    track[i:j] += clip[: j - i] * gain


_ROOM = None


def alley_ir():
    """THE room: a small concrete eskinita. Early reflections off two close walls (6, 11, 17, 23 ms), then a short
    diffuse tail (RT60 about 0.55 s) darkened above 5 kHz. Same seed always: every TUMP file is in the same place."""
    global _ROOM
    if _ROOM is None:
        rng = np.random.default_rng(2026)
        n = int(0.7 * SR)
        t = np.arange(n) / SR
        tail = lowpass(rng.normal(0, 1, n), 5000) * np.exp(-t * 6.9 / 0.55) * np.clip((t - 0.012) / 0.02, 0, 1)
        ir = np.zeros(n)
        ir[0] = 1.0
        for ms, g in ((6, 0.45), (11, -0.32), (17, 0.26), (23, -0.18)):
            ir[int(ms * SR / 1000)] += g
        tail /= np.sqrt(np.sum(tail ** 2))
        _ROOM = (ir, tail)
    return _ROOM


def room(x, wet=0.18):
    """Put a sound in the alley: early reflections always, the tail at `wet`."""
    early, tail = alley_ir()
    dry = signal.fftconvolve(x, early)[: len(x)]
    wetsig = signal.fftconvolve(x, tail)[: len(x)]
    return dry * (1 - wet * 0.5) + wetsig * wet * 2.2


def glue(x, drive=1.15):
    """The shared finishing touch: a gentle tanh saturation, the same 'tape' on every file."""
    return np.tanh(drive * x) / np.tanh(drive)


